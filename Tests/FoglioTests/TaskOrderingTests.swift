import Foundation
@testable import FoglioCore

@MainActor
func taskOrderingTests() {
    Check.suite("Task ordering — placement, filtering, completion, and persistence") {
        let root = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("foglio-order-\(UUID())")
        let store = Store(root: root); store.load()
        defer { try? FileManager.default.removeItem(at: root) }
        let a = TaskItem(label: "Alpha", createdAt: Date(timeIntervalSince1970: 1))
        let hidden = TaskItem(label: "Hidden", createdAt: Date(timeIntervalSince1970: 2))
        let b = TaskItem(label: "Beta", createdAt: Date(timeIntervalSince1970: 3))
        let c = TaskItem(label: "Gamma", createdAt: Date(timeIntervalSince1970: 4))
        for task in [a, hidden, b, c] { store.addTask(task) }
        @MainActor func ids() -> [UUID] { store.manuallyOrderedTasks.map(\.id) }
        Check.equal(ids(), [c.id, b.id, hidden.id, a.id], "new tasks start in reverse insertion order")
        let legacy = Store(root: root.appendingPathComponent("legacy")); legacy.load()
        legacy.replaceAll(with: Archive(tasks: [a, hidden, b, c]))
        Check.expect(legacy.taskWorkspace.taskOrder == nil, "old archives need no ordering field")
        Check.equal(legacy.manuallyOrderedTasks.map(\.id), [c.id, b.id, hidden.id, a.id], "legacy libraries retain newest-first presentation")
        legacy.placeTask(taskId: a.id, statusID: "todo", relativeTo: c.id, autoLog: false)
        let migrated = Store(root: legacy.root); migrated.load()
        Check.equal(migrated.manuallyOrderedTasks.map(\.id), [a.id, c.id, b.id, hidden.id], "first legacy rearrangement persists without losing tasks")
        let savedA = store.tasks.first { $0.id == a.id }!
        Check.expect(store.placeTask(taskId: a.id, statusID: "todo", relativeTo: c.id, autoLog: true), "same-status move upwards succeeds")
        Check.equal(ids(), [a.id, c.id, b.id, hidden.id], "moves before the anchor")
        Check.expect(store.placeTask(taskId: a.id, statusID: "todo", relativeTo: b.id, after: true, autoLog: true), "same-status move downwards succeeds")
        Check.equal(ids(), [c.id, b.id, a.id, hidden.id], "moves after the anchor without an index offset error")
        Check.equal(store.tasks.first { $0.id == a.id }, savedA, "ordering changes neither ticket nor content nor completion")
        Check.equal(store.log.count, 0, "same-status ordering never creates completion logs")
        let filtered = TaskListQuery.filtered(store.manuallyOrderedTasks, status: .all, list: nil, search: "a", preservingOrder: true)
        Check.equal(filtered.map(\.id), [c.id, b.id, a.id], "search preserves manual order and hidden tasks")
        Check.equal(TaskSort.manual.ordered(filtered).map(\.id), filtered.map(\.id), "manual sort preserves the chosen order")
        let beforeInvalid = ids()
        Check.expect(!store.placeTask(taskId: a.id, statusID: "done", relativeTo: b.id, autoLog: true), "anchor in another destination status is rejected")
        Check.expect(!store.placeTask(taskId: a.id, statusID: "done", relativeTo: a.id, autoLog: true), "self-drop is refused without completing")
        Check.expect(!store.placeTask(taskId: UUID(), statusID: "todo", relativeTo: b.id, autoLog: true), "deleted drag source is rejected")
        Check.expect(!store.placeTask(taskId: a.id, statusID: "todo", relativeTo: UUID(), autoLog: true), "deleted anchor is rejected")
        Check.equal(ids(), beforeInvalid, "invalid drops preserve order")
        Check.equal(store.tasks.first { $0.id == a.id }?.done, false, "invalid drop never changes status")
        let review = try! store.addStatus(name: "Review", category: .inProgress)
        store.setStatus(taskId: b.id, statusID: review.id, autoLog: true)
        Check.expect(store.placeTask(taskId: a.id, statusID: review.id, relativeTo: b.id, autoLog: true), "cross-column placement supports custom status")
        Check.equal(store.status(for: store.tasks.first { $0.id == a.id }!).id, review.id, "cross-column drop changes status")
        Check.expect(store.placeTask(taskId: c.id, statusID: review.id, autoLog: true), "column background accepts drops")
        Check.equal(store.manuallyOrderedTasks.filter { store.status(for: $0).id == review.id }.map(\.id), [a.id, b.id, c.id], "background drop appends to destination status")
        Check.expect(store.placeTask(taskId: a.id, statusID: "done", autoLog: true), "drop into Done completes")
        Check.equal(store.log.count, 1, "completion logged once")
        store.placeTask(taskId: a.id, statusID: "done", autoLog: true)
        Check.equal(store.log.count, 1, "repeat drop does not log twice")
        let reopened = Store(root: root); reopened.load()
        Check.equal(reopened.manuallyOrderedTasks.map(\.id), ids(), "order survives relaunch")
        let archive = Exporter.archive(from: store)
        Check.equal(archive.tasks.map(\.id), ids(), "readable export follows manual order too")
        let otherRoot = root.appendingPathComponent("imported")
        let imported = Store(root: otherRoot); imported.load(); imported.replaceAll(with: archive)
        Check.equal(imported.manuallyOrderedTasks.map(\.id), ids(), "archive round trip preserves manual order")
        let new = TaskItem(label: "New task", createdAt: Date(timeIntervalSince1970: 5))
        store.addTask(new)
        Check.equal(ids().first, new.id, "new tasks appear at the top without resetting prior order")
        store.deleteTask(id: hidden.id)
        Check.expect(!store.taskWorkspace.taskOrder!.contains(hidden.id), "deletion removes stale order IDs")
        Check.equal(Set(ids()).count, store.tasks.count, "every remaining task appears exactly once")
        let ties = Store(root: root.appendingPathComponent("ties")); ties.load()
        let first = TaskItem(id: UUID(uuidString: "00000000-0000-0000-0000-000000000001")!, label: "First", createdAt: Date(timeIntervalSince1970: 10))
        let second = TaskItem(id: UUID(uuidString: "FFFFFFFF-FFFF-FFFF-FFFF-FFFFFFFFFFFF")!, label: "Second", createdAt: first.createdAt)
        ties.addTask(first); ties.addTask(second)
        Check.equal(ties.manuallyOrderedTasks.map(\.id), [second.id, first.id], "same-second creation uses insertion order, not random UUID ordering")
        // A blocked metadata file must not claim a successful reorder.
        let workspaceURL = root.appendingPathComponent("task-workspace.json")
        try! FileManager.default.removeItem(at: workspaceURL)
        try! FileManager.default.createDirectory(at: workspaceURL, withIntermediateDirectories: false)
        let beforeFailure = ids()
        Check.expect(!store.placeTask(taskId: new.id, statusID: review.id, relativeTo: b.id, after: true, autoLog: false), "disk failure rejects placement")
        Check.equal(ids(), beforeFailure, "failed write keeps in-memory order")
        Check.equal(store.status(for: store.tasks.first { $0.id == new.id }!).id, "todo", "failed order save cannot partially change status")
    }
}
